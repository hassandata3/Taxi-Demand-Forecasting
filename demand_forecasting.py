"""## Feature Engineering: Create New Binary Features"""

df['city_side'] = df['city_side'].replace({'Rusafa': 0, 'Karkh': 1})
df['is_rainy'] = (df['rain_mm'] > 0).replace({False: 0, True: 1})
df['is_hot'] = (df['temp_c'] >= 40).replace({False: 0, True: 1})

df['is_special_day'] = (df['event_name'] != "None").replace({False : 0 , True : 1})

"""## Map Day Names to Numerical Representation"""

day_mapping = {'Sunday' : 1 , 'Monday' : 2 , 'Tuesday' : 3 , 'Wednesday' : 4 , 'Thursday' : 5 , 'Friday' : 6 , 'Saturday' : 7}
df['day_name'] = df['day_name'].map(day_mapping)

