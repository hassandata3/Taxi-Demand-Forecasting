"""## Feature Engineering: Create Lag and Rolling Mean Features"""

df['lag_1'] = df.groupby('zone_name')['demand'].shift(1)
df['lag_24'] = df.groupby('zone_name')['demand'].shift(24)
df['lag_168'] = df.groupby('zone_name')['demand'].shift(168)
df['lag_336'] = df.groupby('zone_name')['demand'].shift(336)

df['roll_mean_24'] = df.groupby('zone_name')['demand'].transform(lambda x: x.shift(1).rolling(24).mean())
df['roll_mean_168'] = df.groupby('zone_name')['demand'].transform(lambda x: x.shift(1).rolling(168).mean())

df[['hour_ts' , 'zone_name' , 'demand' , 'lag_1' , 'lag_24' , 'lag_168']].head(5)

"""## Drop Rows with NaN Values from Lag Features"""

df = df.dropna(subset=['lag_1' , 'lag_24' , 'lag_168' , 'lag_336']).reset_index(drop=True)

"""## Define Features (X) and Target (y)"""

X = df.drop(['hour_ts' , 'zone_name' , 'demand' , 'event_name' , 'total_requests' , 'no_driver_found' , 'cancelled'] , axis=1)
y = df['demand']

X.shape , y.shape

"""## Split Data into Training and Testing Sets and Scale Features"""

split_date = '2026-02-18'

X_train = X[df['hour_ts'] < split_date]
X_test = X[df['hour_ts'] >= split_date]

y_train = y[df['hour_ts'] < split_date]
y_test = y[df['hour_ts'] >= split_date]

scaler = StandardScaler()
